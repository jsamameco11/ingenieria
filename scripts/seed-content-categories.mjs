function slugify(s) {
  return s
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}

const client = await connect();
try {
  for (const group of SEED) {
    for (let i = 0; i < group.items.length; i++) {
      const name = group.items[i];
      const slug = slugify(name);
      const { rowCount } = await client.query(
        `insert into casa_categories (slug, name, module, position)
         values ($1, $2, $3, $4)
         on conflict (slug) do nothing`,
        [slug, name, group.module, i]
      );
      console.log(rowCount ? `Creada: ${name} (${group.module})` : `Ya existía: ${name}`);
    }
  }
} finally {
  await client.end();
}
