export function extrasDeHospital(cat: CategoriaMinsa) {
  const planta = extrasMinsa(cat).filter((e) => !e.codigo.startsWith("IM-09."));
  const seen = new Set<string>();
  const out: { codigo: string; metrado: number }[] = [];
  for (const e of [...planta, ...extrasEquipamiento(cat)]) {
    if (seen.has(e.codigo)) continue;
    seen.add(e.codigo);
    out.push(e);
  }
  return out;
}
