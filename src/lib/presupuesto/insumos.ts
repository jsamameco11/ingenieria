/** Precio hora-hombre oficial (PRE-06, convenio CAPECO-FTCCP) para cada insumo de mano de obra del catálogo —
 *  única fuente de verdad, para que una corrección en «Mano de obra y jornales» se refleje en todos los APU sin
 *  tener que editar cada insumo por separado. Los insumos "mo" cuyo id no resuelve a una categoría oficial
 *  conservan su precio de catálogo tal cual. */
function conPrecioOficialDeMo(ins: Insumo): Insumo {
  if (ins.kind !== "mo") return ins;
  const oficial = precioOficialDe(ins.id);
  return oficial != null ? { ...ins, precio: oficial } : ins;
}

